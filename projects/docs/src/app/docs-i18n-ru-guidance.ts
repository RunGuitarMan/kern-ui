function normalizedApiDescription(description: string): string {
  return description.replace(/\s+/g, ' ').trim();
}

function translatedApiTerm(term: string): string | undefined {
  return RU_API_TERM[term];
}

function translatedApiDescription(description: string): string | undefined {
  const normalized = normalizedApiDescription(description);
  const exact =
    RU_API_DESCRIPTION_BY_ENGLISH[normalized] ?? RU_PLAYGROUND_DESCRIPTION_BY_ENGLISH[normalized];
  if (exact) return exact;

  let match = normalized.match(/^Human-readable copy for the (.+) state or control\.$/);
  if (match) {
    const term = translatedApiTerm(match[1]);
    if (term) return `Задаёт понятный пользователю текст для состояния или элемента «${term}».`;
  }

  match = normalized.match(/^Defines the component's (.+) behavior or presentation\.$/);
  if (match) {
    const term = translatedApiTerm(match[1]);
    if (term) {
      return `Определяет параметр «${term}», управляющий поведением или представлением компонента.`;
    }
  }

  match = normalized.match(/^Notifies the consumer after the (.+) interaction completes\.$/);
  if (match) {
    const term = translatedApiTerm(match[1]);
    if (term) return `Уведомляет потребителя после завершения взаимодействия «${term}».`;
  }

  match = normalized.match(/^Controls whether the component applies the (.+) behavior\.$/);
  if (match) {
    const term = translatedApiTerm(match[1]);
    if (term) return `Включает или отключает поведение «${term}».`;
  }

  match = normalized.match(/^Controlled (.+) state with a matching Angular model-change output\.$/);
  if (match) {
    const term = translatedApiTerm(match[1]);
    if (term) {
      return `Задаёт управляемое состояние «${term}» и предоставляет соответствующее событие изменения модели Angular.`;
    }
  }

  match = normalized.match(/^Upper or lower bound applied to the (.+) value\.$/);
  if (match) {
    const term = translatedApiTerm(match[1]);
    if (term) return `Задаёт верхнюю или нижнюю границу для значения «${term}».`;
  }

  match = normalized.match(/^Space-separated element ids that (.+)\.$/);
  if (match) {
    const action = RU_ID_ACTION[match[1]];
    if (action) return `Задаёт разделённые пробелами идентификаторы элементов, которые ${action}.`;
  }

  match = normalized.match(/^Stable identifier used by the (.+) contract\.$/);
  if (match) {
    const term = translatedApiTerm(match[1]);
    if (term) return `Задаёт стабильный идентификатор для контракта «${term}».`;
  }

  match = normalized.match(/^Template or projected content used to render (.+)\.$/);
  if (match) {
    const term = translatedApiTerm(match[1]);
    if (term) return `Задаёт шаблон или проецируемое содержимое для области «${term}».`;
  }

  match = normalized.match(/^Ordered domain values supplied to the (.+) collection\.$/);
  if (match) {
    const term = translatedApiTerm(match[1]);
    if (term) return `Передаёт упорядоченные доменные значения в набор «${term}».`;
  }

  match = normalized.match(/^Adds (.+)\.$/);
  if (match) {
    const target = RU_ADD_TARGET[match[1]];
    if (target) return `Добавляет ${target}.`;
  }

  match = normalized.match(/^Changes (.+)\.$/);
  if (match) {
    const target = RU_CHANGE_TARGET[match[1]];
    if (target) return `Изменяет ${target}.`;
  }

  match = normalized.match(/^Chooses (.+)\.$/);
  if (match) {
    const target = RU_CHOOSE_TARGET[match[1]];
    if (target) return `Выбирает ${target}.`;
  }

  match = normalized.match(/^Opens (.+)\.$/);
  if (match) {
    const target = RU_OPEN_TARGET[match[1]];
    if (target) return `Открывает ${target}.`;
  }

  match = normalized.match(/^Sets (.+)\.$/);
  if (match) {
    const target = RU_SET_TARGET[match[1]];
    if (target) return `Задаёт ${target}.`;
  }

  match = normalized.match(/^Shows (.+)\.$/);
  if (match) {
    const target = RU_SHOW_TARGET[match[1]];
    if (target) return `Показывает ${target}.`;
  }

  match = normalized.match(/^Uses locale-aware (.+) copy until explicitly changed\.$/);
  if (match) {
    const target = RU_LOCALE_COPY_TARGET[match[1]];
    if (target) {
      return `Использует текст ${target} с учётом локали, пока он явно не переопределён.`;
    }
  }

  return undefined;
}

const RU_API_KIND_LABEL: Readonly<Record<NonNullable<KernApiRow['kind']>, string>> = Object.freeze({
  input: 'входное свойство',
  model: 'двусторонняя модель',
  output: 'выходное событие',
});

export function russianKeyboardFor(item: CatalogIdentity): readonly string[] {
  return RU_KEYBOARD_BY_COMPONENT[item.id] ?? RU_KEYBOARD_BY_CATEGORY[item.category];
}

export function russianAccessibilityFor(item: CatalogIdentity): readonly string[] {
  return RU_ACCESSIBILITY_BY_COMPONENT[item.id] ?? RU_ACCESSIBILITY_BY_CATEGORY[item.category];
}

export function russianDoFor(item: CatalogIdentity): string {
  const copy = RU_GUIDANCE_BY_COMPONENT[item.id] ?? RU_GUIDANCE_BY_CATEGORY[item.category];
  return RU_GUIDANCE_BY_COMPONENT[item.id]
    ? copy.do
    : `${copy.do} Для ${item.name} применяйте только документированный контракт.`;
}

export function russianDontFor(item: CatalogIdentity): string {
  const copy = RU_GUIDANCE_BY_COMPONENT[item.id] ?? RU_GUIDANCE_BY_CATEGORY[item.category];
  return RU_GUIDANCE_BY_COMPONENT[item.id]
    ? copy.dont
    : `${copy.dont} Не выбирайте ${item.name} только из-за визуального сходства.`;
}

export function russianGuidanceFor(item: CatalogIdentity): RussianCatalogGuidance {
  return Object.freeze({
    keyboard: russianKeyboardFor(item),
    accessibility: russianAccessibilityFor(item),
    do: russianDoFor(item),
    dont: russianDontFor(item),
  });
}

export function russianApiDescriptionFor(row: ApiIdentity): string {
  const translated = translatedApiDescription(row.description);
  if (translated) return translated;

  const kind = row.kind ?? 'input';
  const kindLabel = RU_API_KIND_LABEL[kind];
  return `Для поля «${row.name}» (${kindLabel}) пока используется общее описание на русском языке.`;
}
