import type { KrnConfig, KrnDirection } from './config';
import { createKrnTranslations, KRN_ENGLISH_TRANSLATIONS, type KrnTranslations } from './i18n';

export interface KrnLocalePack {
  readonly locale: string;
  readonly direction: KrnDirection;
  readonly translations: Readonly<KrnTranslations>;
}

export type KrnLocaleConfig = Readonly<
  Required<Pick<KrnConfig, 'locale' | 'direction' | 'translations'>>
>;

/**
 * Adapts a complete locale pack to `provideKrn` without making consumers copy
 * its locale, direction, and translation fields manually.
 */
export function krnLocaleConfig(pack: Readonly<KrnLocalePack>): KrnLocaleConfig {
  return Object.freeze({
    locale: pack.locale,
    direction: pack.direction,
    translations: pack.translations,
  });
}

function russianPlural(value: number, one: string, few: string, many: string): string {
  const absolute = Math.abs(value);
  const lastTwo = absolute % 100;
  if (lastTwo >= 11 && lastTwo <= 14) return many;
  const last = absolute % 10;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}

