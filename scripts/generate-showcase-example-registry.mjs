import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

const workspaceRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const examplesRoot = resolve(workspaceRoot, 'metadata/agent/examples');
const indexPath = resolve(examplesRoot, 'index.json');
const outputPath = resolve(
  workspaceRoot,
  'projects/showcase/examples/src/lib/generated-agent-examples.ts',
);
const writeMode = process.argv.includes('--write');

function digest(value) {
  return `sha256-${createHash('sha256').update(value).digest('hex')}`;
}

const index = JSON.parse(await readFile(indexPath, 'utf8'));
const entries = [];
for (const record of index.examples) {
  if (record.source !== `${record.id}.ts`) {
    throw new Error(`${record.id}: example source must be relative to examples/index.json.`);
  }
  const code = await readFile(resolve(examplesRoot, record.source), 'utf8');
  if (digest(code) !== record.sourceDigest) {
    throw new Error(`${record.id}: example source does not match agent/examples/index.json.`);
  }
  entries.push(
    `${JSON.stringify(record.id)}: Object.freeze({
      id: ${JSON.stringify(record.id)},
      title: ${JSON.stringify(record.title)},
      scenario: ${JSON.stringify(record.scenario)},
      verification: ${JSON.stringify(record.verification)},
      sourceDigest: ${JSON.stringify(record.sourceDigest)},
      code: ${JSON.stringify(code)},
    })`,
  );
}

const source = `/**
 * Generated from the same 131 packed-package AOT examples distributed with KERN.
 * Run \`npm run agent:showcase:write\`; do not edit this file manually.
 */
export interface KernAgentExample {
  readonly id: string;
  readonly title: string;
  readonly scenario: string;
  readonly verification: 'packed-package-aot';
  readonly sourceDigest: string;
  readonly code: string;
}

export const KERN_AGENT_EXAMPLES = Object.freeze({
  ${entries.join(',\n')}
}) satisfies Readonly<Record<string, KernAgentExample>>;

export function findKernAgentExample(id: string): KernAgentExample | undefined {
  return (KERN_AGENT_EXAMPLES as Readonly<Record<string, KernAgentExample>>)[id];
}
`;
const prettierConfig = (await resolveConfig(resolve(workspaceRoot, 'package.json'))) ?? {};
const expected = await format(source, {
  ...prettierConfig,
  parser: 'typescript',
  filepath: outputPath,
});

let actual = null;
try {
  actual = await readFile(outputPath, 'utf8');
} catch (error) {
  if (error?.code !== 'ENOENT') throw error;
}

if (actual !== expected) {
  if (!writeMode) {
    throw new Error(
      'The showcase example registry is missing or stale. Run "npm run agent:showcase:write".',
    );
  }
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, expected, 'utf8');
}

console.log(
  `KERN showcase example registry ${writeMode ? 'written' : 'is current'}: ${entries.length} packed-package AOT examples.`,
);
