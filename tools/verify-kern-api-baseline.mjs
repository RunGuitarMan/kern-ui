import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';

import { format, resolveConfig } from 'prettier';

const workspaceRoot = resolve(import.meta.dirname, '..');
const packageRoot = join(workspaceRoot, 'dist/kern');
const packageManifestPath = join(packageRoot, 'package.json');
const apiRoot = join(workspaceRoot, 'projects/kern/api');
const baselineConfigPath = join(apiRoot, 'entrypoints.json');
const writeMode = process.argv.includes('--write');
const selectedSubpaths = new Set(
  process.argv
    .filter((argument) => argument.startsWith('--subpath='))
    .map((argument) => argument.slice('--subpath='.length)),
);

function fail(message) {
  console.error(`Kern API baseline verification failed: ${message}`);
  process.exitCode = 1;
}

function pathInside(root, candidate) {
  const normalizedRoot = resolve(root);
  const normalizedCandidate = resolve(candidate);
  return (
    normalizedCandidate === normalizedRoot ||
    normalizedCandidate.startsWith(`${normalizedRoot}${sep}`)
  );
}

function typedPackageExports(manifest) {
  return Object.entries(manifest.exports ?? {})
    .filter(
      ([, conditions]) =>
        conditions &&
        typeof conditions === 'object' &&
        typeof conditions.types === 'string' &&
        typeof conditions.default === 'string',
    )
    .map(([subpath, conditions]) => ({
      subpath,
      declarations: conditions.types,
      runtime: conditions.default,
    }))
    .sort((left, right) => left.subpath.localeCompare(right.subpath));
}

function validateBaselineConfig(value) {
  if (!value || typeof value !== 'object' || !Array.isArray(value.entrypoints)) {
    throw new Error('projects/kern/api/entrypoints.json must contain an "entrypoints" array.');
  }

  const seenSubpaths = new Set();
  const seenBaselines = new Set();
  return value.entrypoints.map((entry) => {
    if (
      !entry ||
      typeof entry !== 'object' ||
      typeof entry.subpath !== 'string' ||
      typeof entry.baseline !== 'string'
    ) {
      throw new Error('Every API baseline entry requires string "subpath" and "baseline" fields.');
    }
    if (seenSubpaths.has(entry.subpath)) {
      throw new Error(`Duplicate API baseline subpath: ${entry.subpath}`);
    }
    if (seenBaselines.has(entry.baseline)) {
      throw new Error(`Duplicate API baseline file: ${entry.baseline}`);
    }
    seenSubpaths.add(entry.subpath);
    seenBaselines.add(entry.baseline);
    return entry;
  });
}

function firstDifference(expected, actual) {
  const expectedLines = expected.split('\n');
  const actualLines = actual.split('\n');
  const lineCount = Math.max(expectedLines.length, actualLines.length);
  let index = 0;
  while (index < lineCount && expectedLines[index] === actualLines[index]) {
    index += 1;
  }

  const start = Math.max(0, index - 2);
  const end = Math.min(lineCount, index + 3);
  const rows = [];
  for (let line = start; line < end; line += 1) {
    rows.push(`  ${line + 1} expected: ${expectedLines[line] ?? '<missing>'}`);
    rows.push(`  ${line + 1} actual:   ${actualLines[line] ?? '<missing>'}`);
  }
  return rows.join('\n');
}

async function normalizedBaseline(source, subpath, baselinePath) {
  const prettierConfig = (await resolveConfig(baselinePath)) ?? {};
  return format(
    `/**
 * Committed public API baseline for @kern-ui/angular${subpath === '.' ? '' : subpath.slice(1)}.
 *
 * Generated by tools/verify-kern-api-baseline.mjs. Update intentionally with
 * \`npm run api:baseline:write\` and review the declaration diff.
 */

${source}`,
    {
      ...prettierConfig,
      filepath: baselinePath,
      parser: 'typescript',
    },
  );
}

async function main() {
  if (!existsSync(packageManifestPath)) {
    fail('dist/kern/package.json is missing. Run "npm run build:kern" first.');
    return;
  }
  if (!existsSync(baselineConfigPath)) {
    fail('projects/kern/api/entrypoints.json is missing.');
    return;
  }

  const manifest = JSON.parse(await readFile(packageManifestPath, 'utf8'));
  const configured = validateBaselineConfig(JSON.parse(await readFile(baselineConfigPath, 'utf8')));
  const discovered = typedPackageExports(manifest);
  const configuredBySubpath = new Map(configured.map((entry) => [entry.subpath, entry]));
  const discoveredBySubpath = new Map(discovered.map((entry) => [entry.subpath, entry]));

  for (const entrypoint of discovered) {
    if (!configuredBySubpath.has(entrypoint.subpath)) {
      fail(
        `typed package export "${entrypoint.subpath}" has no committed baseline configuration. ` +
          'Add it to projects/kern/api/entrypoints.json.',
      );
    }
  }
  for (const entry of configured) {
    if (!discoveredBySubpath.has(entry.subpath)) {
      fail(
        `configured entrypoint "${entry.subpath}" is not present as a typed export in dist/kern/package.json.`,
      );
    }
  }
  if (process.exitCode) return;
  for (const subpath of selectedSubpaths) {
    if (!configuredBySubpath.has(subpath)) {
      fail(`selected entrypoint "${subpath}" has no baseline configuration.`);
    }
  }
  if (process.exitCode) return;

  for (const entry of configured) {
    if (selectedSubpaths.size > 0 && !selectedSubpaths.has(entry.subpath)) continue;
    const discoveredEntrypoint = discoveredBySubpath.get(entry.subpath);
    const declarationsPath = resolve(packageRoot, discoveredEntrypoint.declarations);
    const runtimePath = resolve(packageRoot, discoveredEntrypoint.runtime);
    const baselinePath = resolve(apiRoot, entry.baseline);

    if (!pathInside(packageRoot, declarationsPath) || !pathInside(packageRoot, runtimePath)) {
      fail(`entrypoint "${entry.subpath}" resolves outside the built package.`);
      continue;
    }
    if (!pathInside(apiRoot, baselinePath)) {
      fail(`baseline for "${entry.subpath}" resolves outside projects/kern/api.`);
      continue;
    }
    if (!existsSync(declarationsPath) || !existsSync(runtimePath)) {
      fail(`entrypoint "${entry.subpath}" references a missing declaration or runtime artifact.`);
      continue;
    }

    const generated = await normalizedBaseline(
      await readFile(declarationsPath, 'utf8'),
      entry.subpath,
      baselinePath,
    );

    if (writeMode) {
      await mkdir(dirname(baselinePath), { recursive: true });
      await writeFile(baselinePath, generated, 'utf8');
      console.log(`Wrote ${relative(workspaceRoot, baselinePath)}.`);
      continue;
    }

    if (!existsSync(baselinePath)) {
      fail(
        `baseline for "${entry.subpath}" is missing at ${relative(workspaceRoot, baselinePath)}. ` +
          'Run "npm run api:baseline:write".',
      );
      continue;
    }

    const committed = await readFile(baselinePath, 'utf8');
    if (committed !== generated) {
      fail(
        `public declarations changed for "${entry.subpath}". ` +
          'Review the change, update versioning notes, then run "npm run api:baseline:write".\n' +
          firstDifference(committed, generated),
      );
    }
  }

  if (!process.exitCode) {
    console.log(
      `Kern API baselines verified: ${
        selectedSubpaths.size || configured.length
      } typed package entrypoint(s).`,
    );
  }
}

await main();
